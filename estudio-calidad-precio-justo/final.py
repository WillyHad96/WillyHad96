RF=0.02
def st(r,lab,cost,n=None):
    r=r-cost; k=len(r)
    cagr=np.prod(1+r)**(1/k)-1; ar=r.mean(); vol=r.std(ddof=1)
    beta=np.cov(r,spy,ddof=1)[0,1]/np.var(spy,ddof=1)
    alpha=(ar-RF)-beta*(spy.mean()-RF)
    nm=f"{n.mean():5.0f}" if n is not None else "    —"
    print(f"{lab:<30}{nm}{100*cagr:>8.2f}{100*vol:>7.1f}{(cagr-RF)/vol:>8.2f}{beta:>6.2f}{100*alpha:>7.2f}{100*r.min():>8.1f}{100*np.mean(r>spy):>7.1f}")
print(f"{'cartera':<30}{'n/año':>5}{'CAGR':>8}{'vol':>7}{'Sharpe':>8}{'beta':>6}{'alfa':>7}{'peor':>8}{'%>SPY':>7}")
