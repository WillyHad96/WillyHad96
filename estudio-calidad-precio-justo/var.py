def parse(s):
    d={}
    for r in s.split(';'):
        y,n,a,b=r.split(','); d[int(y)]=(int(n),float(a)/100,float(b)/100)
    return d
D={k:parse(v) for k,v in raw.items()}
def cagr(x):
    p=1.0
    for v in x: p*=(1+v)
    return p**(1/len(x))-1
